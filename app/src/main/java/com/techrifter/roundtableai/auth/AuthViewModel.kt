package com.techrifter.roundtableai.auth

import android.app.Activity
import android.app.Application
import android.util.Log
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import androidx.lifecycle.AndroidViewModel
import androidx.lifecycle.viewModelScope
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.techrifter.roundtableai.network.SessionApi
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.launch
import kotlinx.coroutines.tasks.await

private const val TAG = "AuthViewModel"

sealed class AuthState {
    /** Still checking if the user is already signed in. */
    data object Loading : AuthState()
    /** Signed in with a valid Firebase user. */
    data class SignedIn(val user: FirebaseUser) : AuthState()
    /** Not signed in — show the sign-in screen. */
    data object SignedOut : AuthState()
    /** Sign-in attempt failed with an error message. */
    data class Error(val message: String) : AuthState()
}

class AuthViewModel(application: Application) : AndroidViewModel(application) {

    private val auth = FirebaseAuth.getInstance()
    private val accountApi = SessionApi { getIdToken() }

    private val _authState = MutableStateFlow<AuthState>(AuthState.Loading)
    val authState: StateFlow<AuthState> = _authState
    private val _isGoogleSigningIn = MutableStateFlow(false)
    val isGoogleSigningIn: StateFlow<Boolean> = _isGoogleSigningIn

    init {
        // If a Firebase session is already persisted on this device, skip the sign-in screen.
        val current = auth.currentUser
        _authState.value = if (current != null) AuthState.SignedIn(current) else AuthState.SignedOut
    }

    /**
     * Resolves the Web Client ID for Google One Tap.
     * Checks for the string auto-generated by the google-services plugin (default_web_client_id),
     * or a custom 'google_web_client_id' entry in strings.xml.
     */
    private fun getWebClientId(activity: Activity): String {
        val resId = activity.resources.getIdentifier("default_web_client_id", "string", activity.packageName)
        if (resId != 0) {
            val id = activity.getString(resId)
            if (id.isNotBlank()) return id
        }
        val customResId = activity.resources.getIdentifier("google_web_client_id", "string", activity.packageName)
        if (customResId != 0) {
            val id = activity.getString(customResId)
            if (id.isNotBlank()) return id
        }
        throw IllegalStateException(
            "Google Web Client ID not found. Ensure Google Sign-In is enabled in Firebase Console and re-download google-services.json, or add 'google_web_client_id' in strings.xml."
        )
    }

    /**
     * Returns a valid (non-expired) Firebase ID token for the current user.
     * Firebase caches the token and refreshes it automatically when < 5 min remain.
     * Returns null if the user is not signed in.
     */
    suspend fun getIdToken(): String? = try {
        auth.currentUser?.getIdToken(/* forceRefresh = */ false)?.await()?.token
    } catch (t: Throwable) {
        Log.e(TAG, "getIdToken failed — forcing refresh", t)
        // One retry with forceRefresh in case the cached token is corrupted.
        try {
            auth.currentUser?.getIdToken(/* forceRefresh = */ true)?.await()?.token
        } catch (t2: Throwable) {
            Log.e(TAG, "getIdToken forceRefresh also failed", t2)
            null
        }
    }

    /**
     * Signs in with email and password.
     */
    fun signInWithEmail(email: String, password: String) {
        val cleanEmail = email.trim()
        if (cleanEmail.isEmpty()) {
            _authState.value = AuthState.Error("Please enter your email address.")
            return
        }
        if (password.isEmpty()) {
            _authState.value = AuthState.Error("Please enter your password.")
            return
        }
        viewModelScope.launch {
            _authState.value = AuthState.Loading
            try {
                val result = auth.signInWithEmailAndPassword(cleanEmail, password).await()
                val user = result.user
                if (user != null) {
                    _authState.value = AuthState.SignedIn(user)
                } else {
                    _authState.value = AuthState.Error("Sign-in succeeded but user is null")
                }
            } catch (t: Throwable) {
                Log.e(TAG, "signInWithEmail failed", t)
                val msg = when {
                    t.message?.contains("user-not-found", ignoreCase = true) == true ||
                    t.message?.contains("invalid-credential", ignoreCase = true) == true ->
                        "Invalid email or password."
                    t.message?.contains("invalid-email", ignoreCase = true) == true ->
                        "Please enter a valid email address."
                    t.message?.contains("too-many-requests", ignoreCase = true) == true ->
                        "Too many failed attempts. Please try again later."
                    else -> t.localizedMessage ?: "Failed to sign in. Please try again."
                }
                _authState.value = AuthState.Error(msg)
            }
        }
    }

    /**
     * Registers a new account with email and password.
     */
    fun signUpWithEmail(email: String, password: String) {
        val cleanEmail = email.trim()
        if (cleanEmail.isEmpty()) {
            _authState.value = AuthState.Error("Please enter your email address.")
            return
        }
        if (
            password.length < 5 ||
            password.none(Char::isUpperCase) ||
            password.none(Char::isLowerCase) ||
            password.none(Char::isDigit) ||
            password.none { !it.isLetterOrDigit() && !it.isWhitespace() }
        ) {
            _authState.value = AuthState.Error(
                "Use at least 5 characters with uppercase, lowercase, a number, and a symbol."
            )
            return
        }
        viewModelScope.launch {
            _authState.value = AuthState.Loading
            try {
                val result = auth.createUserWithEmailAndPassword(cleanEmail, password).await()
                val user = result.user
                if (user != null) {
                    _authState.value = AuthState.SignedIn(user)
                } else {
                    _authState.value = AuthState.Error("Account creation succeeded but user is null")
                }
            } catch (t: Throwable) {
                Log.e(TAG, "signUpWithEmail failed", t)
                val msg = when {
                    t.message?.contains("email-already-in-use", ignoreCase = true) == true ->
                        "An account with this email already exists. Try signing in."
                    t.message?.contains("invalid-email", ignoreCase = true) == true ->
                        "Please enter a valid email address."
                    t.message?.contains("weak-password", ignoreCase = true) == true ->
                        "Password is too weak. Please choose a stronger password."
                    else -> t.localizedMessage ?: "Failed to create account. Please try again."
                }
                _authState.value = AuthState.Error(msg)
            }
        }
    }

    fun clearError() {
        if (_authState.value is AuthState.Error) {
            _authState.value = AuthState.SignedOut
        }
    }

    /**
     * Launches Google One Tap via Credential Manager. On success, signs into Firebase
     * with the Google credential and emits [AuthState.SignedIn].
     *
     * [activity] must be the foreground Activity — Credential Manager needs it to
     * show the account picker sheet.
     */
    fun signInWithGoogle(activity: Activity) {
        if (_isGoogleSigningIn.value || _authState.value is AuthState.Loading) return
        viewModelScope.launch {
            _isGoogleSigningIn.value = true
            try {
                val webClientId = getWebClientId(activity)
                Log.d(TAG, "signInWithGoogle: using webClientId=${webClientId.take(16)}... (length=${webClientId.length})")

                val credentialManager = CredentialManager.create(activity)
                val googleIdOption = GetGoogleIdOption.Builder()
                    // Show ALL Google accounts on the device, not just previously used ones.
                    .setFilterByAuthorizedAccounts(false)
                    .setServerClientId(webClientId)
                    .setAutoSelectEnabled(false)
                    .build()

                val request = GetCredentialRequest.Builder()
                    .addCredentialOption(googleIdOption)
                    .build()

                val result = credentialManager.getCredential(
                    context = activity,
                    request = request,
                )

                val credential = result.credential
                if (credential is CustomCredential &&
                    credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
                ) {
                    val googleIdTokenCredential = GoogleIdTokenCredential.createFrom(credential.data)
                    val firebaseCredential = GoogleAuthProvider.getCredential(
                        googleIdTokenCredential.idToken,
                        null,
                    )
                    val authResult = auth.signInWithCredential(firebaseCredential).await()
                    val user = authResult.user
                    if (user != null) {
                        Log.d(TAG, "Signed in as ${user.email} uid=${user.uid}")
                        _authState.value = AuthState.SignedIn(user)
                    } else {
                        _authState.value = AuthState.Error("Sign-in succeeded but user is null")
                    }
                } else {
                    _authState.value = AuthState.Error("Unexpected credential type: ${credential.type}")
                }
            } catch (e: GetCredentialCancellationException) {
                // User dismissed the picker — just go back to SignedOut, don't show an error.
                Log.d(TAG, "User cancelled Google Sign-In picker")
                _authState.value = AuthState.SignedOut
            } catch (e: NoCredentialException) {
                Log.e(TAG, "NoCredentialException: No Google credentials available on device/project", e)
                _authState.value = AuthState.Error(
                    "No Google account found on this device, or debug SHA-1 fingerprint is missing in Firebase Console."
                )
            } catch (e: GetCredentialException) {
                Log.e(TAG, "Credential Manager error: ${e::class.java.simpleName}", e)
                _authState.value = AuthState.Error("Sign-in failed: ${e.localizedMessage}")
            } catch (t: Throwable) {
                Log.e(TAG, "Firebase sign-in error", t)
                _authState.value = AuthState.Error("Sign-in failed: ${t.localizedMessage}")
            } finally {
                _isGoogleSigningIn.value = false
            }
        }
    }

    fun signOut() {
        auth.signOut()
        _authState.value = AuthState.SignedOut
    }

    suspend fun deleteAccount(): Result<Unit> {
        return try {
            accountApi.deleteAccount()
            Result.success(Unit)
        } catch (e: CancellationException) {
            throw e
        } catch (t: Throwable) {
            Result.failure(t)
        }
    }
}
